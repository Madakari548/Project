#!/usr/bin/env bash
set -Eeuo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
need() { test -s "$1" || { echo "Missing build output: $1" >&2; exit 1; }; }
A="$ROOT/webdroid/runtime/raspi3ap"
X="$ROOT/webdroid/runtime/alpine-x86_64"
need "$A/out.js"
need "$A/qemu-system-aarch64.wasm"
need "$A/qemu-system-aarch64.worker.js"
need "$A/qemu-system-aarch64.data"
need "$A/load.js"
need "$X/out.js"
need "$X/qemu-system-x86_64.wasm"
need "$X/qemu-system-x86_64.worker.js"
need "$X/load-rootfs.js"
need "$X/load-kernel.js"
need "$X/load-initramfs.js"
need "$X/load-rom.js"
need "$X/dist/stack.js"
echo "Both QEMU/Wasm engines and their Linux smoke-test assets are present."
